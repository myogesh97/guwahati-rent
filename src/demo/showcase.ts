/** The fields every stored pin has, before the record's own answers. */
const BLANK: Omit<
  PublicPin,
  'id' | 'property_type' | 'bhk' | 'rent' | 'furnishing' | 'lat' | 'lng' | 'created_at'
> = {
  kind: 'rent',
  gated: false,
  maintenance_incl: null,
  deposit_months: null,
  sqft: null,
  parking_cars: 0,
  society_name: null,
  occupants: null,
  pets_allowed: null,
  waterlogging: 'unknown',
  water_supply: null,
  power_backup: null,
  pg_meals: null,
  pg_gender: null,
  one_liner: null,
  locality_slug: null,
  is_outlier: false,
  source: 'user',
  location_approx: false,
  conditions_as_of: null,
  sqft_band: null,
};

/** One record stored the way submit-pin stores a form answer. */
function store({ area: _area, at, on, monsoon, size, type, bhk, ...answers }: Rec, i: number) {
  const waterlog_answer =
    monsoon === 'no' || monsoon === 'unknown' ? monsoon : monsoon ? 'yes' : undefined;
  const { waterlog_answer: _a, ...kept } = pruneConditions({
    ...answers,
    waterlog_answer,
    waterlog_where: Array.isArray(monsoon) ? [...monsoon] : undefined,
  });
  const pin: Record<string, unknown> = {
    ...BLANK,
    ...kept,
    id: `${SHOWCASE_PREFIX}${String(i + 1).padStart(3, '0')}`,
    property_type: type,
    bhk: NO_BHK_TYPES.includes(type) ? 0 : (bhk ?? 1),
    waterlogging: waterlogSummary(waterlog_answer, kept.waterlog_where),
    sqft_band: size ?? null,
    locality_slug: nearestLocality(at[0], at[1], LOCALITIES),
    created_at: new Date(on).toISOString(),
    lat: at[0],
    lng: at[1],
  };
  if (type !== 'pg') pin.pg_meals = pin.pg_gender = null;
  for (const k of Object.keys(pin)) if (pin[k] === undefined) pin[k] = null;
  return pin as unknown as PublicPin;
}

/** The 45 illustrative pins, fresh objects on every call (the app mutates pins it holds). */
export function showcasePins(): PublicPin[] {
  return RECORDS.map(store);
}

